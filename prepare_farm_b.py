"""Prepare farm B (Penmanshiel, Cubico open data) in farm B's own table layout.

Expected in data/penmanshiel/ (download from https://zenodo.org/records/16807304):
    Penmanshiel_SCADA_2016_WT01-10_3107.zip
    Penmanshiel_SCADA_2016_WT11-15_3107.zip
    Penmanshiel_WT_static.csv
Writes build/import_b/*.csv for farm_b/load.sql. The source files are never modified.

Farm B has no maintenance records in the open data, so work orders are SYNTHETIC: they are
generated from real alarm events with a farm-B repair policy that deliberately differs from
farm A, to show what a cross-farm query can reveal. That difference is designed, not found.
"""

import csv
import hashlib
import re
import sys
import zipfile
from datetime import datetime, timedelta
from pathlib import Path

SOURCE = Path(sys.argv[1] if len(sys.argv) > 1 else "data/penmanshiel")
CURATED = Path("data/curated")
OUT = Path("build/import_b")
SITE = "penmanshiel"
SIGNALS = {  # farm B's own signal names <- Cubico column labels (first match wins)
    "P_avg": ("Power (kW)",),
    "E_exp": ("Energy Export (kWh)",),
    "WS_avg": ("Wind speed (m/s)",),
    "T_gear_oil": ("Gear oil temperature (°C)", "Gear oil temperature (Â°C)"),
}
POLICY = {  # synthetic farm-B repair policy, cycled per fault
    "GearBearingOverheating": ["Re-lubrication and temperature monitoring"] * 3 + ["Replaced gearbox bearing"],
    "GearboxBearingWear": ["Re-lubrication and temperature monitoring", "Re-lubrication and temperature monitoring", "Replaced gearbox bearing"],
    "GearboxLubricationFault": ["Re-lubrication and monitoring", "Replaced gear oil pump"],
    "GearOilContamination": ["Oil change and filter replacement"],
    "GeneratorCoolingFault": ["Cleaned fan and reset", "Replaced generator fan"],
}
PER_FAULT = 8


def rows(path):
    with path.open(newline="", encoding="utf-8-sig") as stream:
        yield from csv.DictReader(stream)


def write_csv(name, columns, data):
    count = 0
    with (OUT / name).open("w", newline="", encoding="utf-8") as stream:
        writer = csv.writer(stream)
        writer.writerow(columns)
        for row in data:
            writer.writerow(row)
            count += 1
    return count


def utc(text):
    return "" if text in ("", "-", "NaN") else text + "+00:00"


def number(title):
    digits = re.findall(r"\d+", title)
    if not digits:
        raise ValueError(f"No turbine number in {title!r}")
    return int(digits[-1])


def main():
    zips = sorted(SOURCE.glob("Penmanshiel_SCADA_2016*.zip"))
    static = SOURCE / "Penmanshiel_WT_static.csv"
    if not zips or not static.exists():
        raise SystemExit(f"Put the Penmanshiel 2016 SCADA zip(s) and Penmanshiel_WT_static.csv in {SOURCE}/ first.")
    for path in [*zips, static]:
        print(f"{path.name}: md5 {hashlib.md5(path.read_bytes()).hexdigest()}")
    OUT.mkdir(parents=True, exist_ok=True)

    write_csv("data_sources.csv", ["source_ref", "kind", "origin", "published", "owner_org", "licence", "terms"], [
        ["penmanshiel-2016", "observed_source", "https://doi.org/10.5281/zenodo.16807304", "2025-08-12", "Cubico Sustainable Investments Ltd", "CC BY 4.0", "Attribute Cubico and cite the Zenodo record"],
        ["farmb-synthetic-work-orders", "synthetic_demo", "Generated by prepare_farm_b.py from real alarms with a designed repair policy", "2026-11-14", "V1 project team", "Not specified", "Demo only; the farm-A/farm-B difference is designed, not observed"],
        ["v11-curated-fault-rules", "curated_demo", "Alarm-to-fault rules written for this demo (data/curated)", "2026-11-14", "V1 project team", "Not specified", "Illustrative expert-style rules; confidence values are not validated"],
        ["farmb-component-assumption", "derived_assumption", "Each Senvion MM82 is assumed to have one gearbox and one generator", "2026-11-14", "V1 project team", "Not specified", "Component identities are assumed from the turbine model"],
    ])
    turbines = [t for t in rows(static) if (t.get("Title") or "").strip()]
    first = turbines[0]
    write_csv("site.csv", ["site_code", "site_name", "country", "source_ref"],
              [[SITE, first.get("Wind Farm", "Penmanshiel"), first.get("Country", "UK"), "penmanshiel-2016"]])
    codes = {number(t["Title"]): f"T{number(t['Title']):02d}" for t in turbines}
    write_csv("wtg.csv", ["wtg_code", "site_code", "wtg_label", "make", "type_name", "rated_kw", "lat", "lon"],
              ([codes[number(t["Title"])], SITE, t["Title"], t["Manufacturer"], t["Model"], t["Rated power (kW)"], t["Latitude"], t["Longitude"]] for t in turbines))

    alarms = []
    tenmin_count = 0
    with (OUT / "tenmin.csv").open("w", newline="", encoding="utf-8") as tenmin_file, \
         (OUT / "alarm_log.csv").open("w", newline="", encoding="utf-8") as alarm_file:
        tenmin = csv.writer(tenmin_file)
        alarm = csv.writer(alarm_file)
        tenmin.writerow(["src_file", "src_line", "wtg_code", "ts", "signal_name", "val"])
        alarm.writerow(["src_file", "line_no", "wtg_code", "t_from", "t_to", "severity", "alarm_code", "alarm_text"])
        for archive in zips:
            with zipfile.ZipFile(archive) as z:
                for name in z.namelist():
                    match = re.search(r"(Turbine_Data|Status)_Penmanshiel_(\d+)_2016", Path(name).name)
                    if not match:
                        continue
                    wtg = codes.get(int(match.group(2)))
                    if not wtg:
                        raise ValueError(f"{name}: turbine {match.group(2)} is not in the static table")
                    member = Path(name).name
                    with z.open(name) as raw:
                        text = (line.decode("utf-8-sig").rstrip("\r\n") for line in raw)
                        if match.group(1) == "Turbine_Data":
                            header = next(line[2:] for line in text if line.startswith("# Date and time,"))
                            columns = next(csv.reader([header]))
                            index = {}
                            for signal, labels in SIGNALS.items():
                                found = next((columns.index(label) for label in labels if label in columns), None)
                                if found is None:
                                    print(f"warning: {member} has no column for {signal}")
                                else:
                                    index[signal] = found
                            for line_no, row in enumerate(csv.reader(text), 1):
                                for signal, column in index.items():
                                    if row[column] not in ("", "NaN"):
                                        tenmin.writerow([member, line_no, wtg, utc(row[0]), signal, row[column]])
                                        tenmin_count += 1
                        else:
                            reader = csv.DictReader(line for line in text if not line.startswith("#"))
                            for line_no, row in enumerate(reader, 1):
                                record = [member, line_no, wtg, utc(row["Timestamp start"]), utc(row["Timestamp end"]), row["Status"], row["Code"], row["Message"]]
                                alarm.writerow(record)
                                alarms.append(record)

    faults = list(rows(CURATED / "fault_conditions.csv"))
    write_csv("fault_catalog.csv", ["fault_ref", "title", "part_type", "details"],
              ([f["fault_code"], f["label"], f["component_type"], f["description"]] for f in faults))
    rules = list(rows(CURATED / "alarm_fault_rules.csv"))
    write_csv("alarm_rules.csv", ["rule_ref", "pattern", "fault_ref", "weight", "why"],
              ([r["rule_id"], r["message_pattern"], r["fault_code"], r["confidence"], r["rationale"]] for r in rules))

    part = {f["fault_code"]: f["component_type"] for f in faults}
    orders, seen, used = [], set(), {code: 0 for code in POLICY}
    for src_file, line_no, wtg, t_from, _, _, _, message in sorted(alarms, key=lambda a: a[3]):
        matched = [r for r in rules if re.search(r["message_pattern"], message, re.I)]
        if not matched:
            continue
        best = max(matched, key=lambda r: float(r["confidence"]))["fault_code"]
        start = datetime.fromisoformat(t_from)
        key = (wtg, best, start.isocalendar()[:2])
        if key in seen or used[best] >= PER_FAULT:
            continue
        seen.add(key)
        action = POLICY[best][used[best] % len(POLICY[best])]
        used[best] += 1
        opened = (start + timedelta(days=1)).replace(hour=8, minute=0, second=0)
        closed = opened + timedelta(hours=30 if action.startswith("Replaced") else 3)
        orders.append([f"WO-B{len(orders) + 1:04d}", wtg, src_file, line_no, best, part[best], action,
                       opened.isoformat(), closed.isoformat(), f"Demo crew {len(orders) % 3 + 1}",
                       "Synthetic work order generated from a real alarm", "farmb-synthetic-work-orders"])
    write_csv("work_orders.csv", ["wo_number", "wtg_code", "alarm_file", "alarm_line", "fault_ref", "part_type", "job_type",
                                  "opened", "closed", "crew_name", "notes", "source_ref"], orders)
    if not alarms or not tenmin_count:
        raise SystemExit("No turbine data or status rows were found in the archives.")
    print(f"Prepared farm B: {len(turbines)} turbines, {tenmin_count} ten-minute values, {len(alarms)} alarms, "
          f"{len(orders)} synthetic work orders")


if __name__ == "__main__":
    main()
